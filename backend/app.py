import io
import json
from functools import lru_cache
from pathlib import Path

import numpy as np
from flask import Flask, jsonify, render_template, request
from PIL import Image, UnidentifiedImageError

BASE_DIR = Path(__file__).resolve().parent.parent
FRONTEND_DIR = BASE_DIR / "frontend"
MODEL_DIR = BASE_DIR / "models"
MAX_UPLOAD_BYTES = 4 * 1024 * 1024
IMAGE_SIZE = (64, 64)

app = Flask(
    __name__,
    template_folder=str(FRONTEND_DIR / "templates"),
    static_folder=str(FRONTEND_DIR / "static"),
)
app.config["MAX_CONTENT_LENGTH"] = MAX_UPLOAD_BYTES


@lru_cache(maxsize=2)
def load_model(mode):
    """Load model and labels on demand; keep the app usable without ML dependencies."""
    model_path = MODEL_DIR / f"{mode}.keras"
    labels_path = MODEL_DIR / f"{mode}_labels.json"
    if not model_path.is_file() or not labels_path.is_file():
        return None, None
    try:
        import tensorflow as tf

        model = tf.keras.models.load_model(model_path)
        labels = json.loads(labels_path.read_text(encoding="utf-8"))
        return model, labels
    except ImportError:
        raise RuntimeError(
            "TensorFlow is not installed. Install requirements-ml.txt to run predictions."
        )
    except Exception as exc:
        raise RuntimeError(f"Could not load the {mode} model: {exc}") from exc


@app.get("/")
def index():
    return render_template("index.html")


@app.get("/api/health")
def health():
    models = {}
    for mode in ("digits", "alphabet"):
        try:
            model, _labels = load_model(mode)
        except RuntimeError as exc:
            models[mode] = {"available": False, "error": str(exc)}
        else:
            if model is None:
                models[mode] = {
                    "available": False,
                    "error": (
                        f"No trained {mode} model found on this server. "
                        f"Expected models/{mode}.keras and models/{mode}_labels.json."
                    ),
                }
            else:
                models[mode] = {"available": True}
    return jsonify(
        {
            "status": "ok",
            "models": models,
        }
    )


@app.errorhandler(413)
def too_large(_error):
    return jsonify(error="Image is too large. Maximum upload size is 4 MB."), 413


@app.post("/api/predict")
def predict():
    mode = request.form.get("mode", "digits").strip().lower()
    if mode not in {"digits", "alphabet"}:
        return jsonify(error="Invalid mode. Choose digits or alphabet."), 400

    uploaded = request.files.get("image")
    if not uploaded or not uploaded.filename:
        return jsonify(error="Please choose an image file."), 400
    raw = uploaded.read(MAX_UPLOAD_BYTES + 1)
    if len(raw) > MAX_UPLOAD_BYTES:
        return jsonify(error="Image is too large. Maximum upload size is 4 MB."), 413

    try:
        with Image.open(io.BytesIO(raw)) as source:
            if source.width * source.height > 20_000_000:
                return jsonify(error="Image dimensions are too large."), 400
            image = source.convert("RGB").resize(IMAGE_SIZE, Image.Resampling.BILINEAR)
    except (UnidentifiedImageError, OSError, ValueError):
        return jsonify(error="Unsupported or invalid image. Upload JPG, PNG, or WEBP."), 400

    try:
        model, labels = load_model(mode)
    except RuntimeError as exc:
        return jsonify(error=str(exc)), 503
    if model is None:
        return (
            jsonify(error=f"No trained {mode} model found. Train one and place it in models/."),
            503,
        )

    image_array = np.asarray(image, dtype=np.float32) / 255.0
    predictions = np.asarray(model.predict(np.expand_dims(image_array, axis=0), verbose=0))[0]
    index = int(np.argmax(predictions))
    confidence = float(predictions[index])
    if isinstance(labels, list):
        label = str(labels[index])
    else:
        label = str(labels.get(str(index), labels.get(index, index)))

    uncertain = confidence < 0.70
    return jsonify(
        label="Uncertain" if uncertain else label,
        predicted_label=label,
        confidence=confidence,
        message=(
            "Confidence is low; try a clearer image."
            if uncertain
            else "Prediction generated by the trained model."
        ),
    )
